    // 0..8 samples along it (left to right, top to bottom); none = `fill`
    std::vector<Color> edges[4];
    bool hasEdges() const { return !edges[0].empty() || !edges[1].empty() || !edges[2].empty() || !edges[3].empty(); }
    bool hasClip = false;

bool readVec3(const JVal *v, v3 &out) {
    if (!v || v->type != JVal::Arr || v->a.size() != 3) return false;
    for (const JVal &e : v->a)
        if (e.type != JVal::Num || !std::isfinite(e.n)) return false;
    out = {float(v->a[0].n), float(v->a[1].n), float(v->a[2].n)};
    return true;
}

bool parseSpec(const std::string &text, Spec &out, std::string &err) {
    JVal root;
    if (!JParser(text).parse(root, err)) return false;
    if (root.type != JVal::Obj) { err = "spec is not an object"; return false; }
    out = Spec{};
    {
        const double sq = root.num("seq", 0);
        out.seq = std::isfinite(sq) ? (long long)std::clamp(sq, -9.0e18, 9.0e18) : 0;
    }
    out.dial = float(root.num("dial", 0.5));
    out.reduceMotion = root.boolean("reduceMotion", false);
    {
        const float d = float(root.num("roomDim", 0));
        out.roomDim = std::isfinite(d) ? std::clamp(d, 0.f, 0.9f) : 0.f;
    }
    {
        const float u = float(root.num("unitM", 0.369));
        out.unitM = std::isfinite(u) && u > 0.01f && u < 10.f ? u : 0.369f;
    }
    auto finite = [](float v) { return std::isfinite(v) ? v : 0.f; };
    if (const JVal *m = root.get("masks"); m && m->type == JVal::Arr) {
        for (const JVal &q : m->a) {
            WorldMask wm;
            if (q.type == JVal::Obj && readVec3(q.get("O"), wm.O) && readVec3(q.get("U"), wm.U) && readVec3(q.get("V"), wm.V) &&
                length(wm.U) > 1e-4f && length(wm.V) > 1e-4f && length(wm.U) < 20.f && length(wm.V) < 20.f &&
                out.masks.size() < size_t(kMaxExtraMasks))
                out.masks.push_back(wm);
        }
    }
    const JVal *surfs = root.get("surfaces");
    if (!surfs || surfs->type != JVal::Arr) return true;
    for (const JVal &s : surfs->a) {
        if (s.type != JVal::Obj) continue;
        SurfSpec ss;
        ss.name = s.str("name", "");
        ss.overlayKey = s.str("overlayKey", "");
        ss.texW = int(s.num("texW", 0));
        ss.texH = int(s.num("texH", 0));
        ss.radius = float(s.num("radius", 0));
        ss.material = s.str("material", "window");
        ss.visible = s.boolean("visible", true);
        ss.armed = !ss.visible && s.boolean("armed", false);
        readPhase(s, ss.ph);
        if (const JVal *m = s.get("morph"); m && m->type == JVal::Obj) {
            ss.morphToken = m->str("token", "");
            ss.morphAtMs = m->num("at", 0);
            ss.hasMorph = !ss.morphToken.empty() && std::isfinite(ss.morphAtMs) && ss.morphAtMs > 0;
        }
        if (ss.name.empty() || ss.name.size() > 128 || ss.texW <= 0 || ss.texH <= 0 || ss.texW > 8192 || ss.texH > 8192) continue;
        if (const JVal *sh = s.get("shapes"); sh && sh->type == JVal::Arr) {
            ss.hasShapes = true;
            for (const JVal &q : sh->a) {
                ShapeSpec p{float(q.num("x", 0)), float(q.num("y", 0)), float(q.num("w", 0)), float(q.num("h", 0)),
                            float(q.num("r", ss.radius))};
                // clip to the texture
                const float x0 = std::max(0.f, p.x), y0 = std::max(0.f, p.y);
                const float x1 = std::min(float(ss.texW), p.x + p.w), y1 = std::min(float(ss.texH), p.y + p.h);
                if (x1 - x0 < 1 || y1 - y0 < 1) continue;
                p = {x0, y0, x1 - x0, y1 - y0, std::max(0.f, p.r)};
                ss.shapes.push_back(p);
            }
        }
        if (const JVal *q = s.get("quad"); q && q->type == JVal::Obj)
            ss.hasQuad = readVec3(q->get("O"), ss.qO) && readVec3(q->get("U"), ss.qU) && readVec3(q->get("V"), ss.qV);
        if (const JVal *sl = s.get("slabs"); sl && sl->type == JVal::Arr) {
            for (const JVal &q : sl->a) {
                SlabSpec b;
                b.id = q.str("id", "");
                if (const JVal *idn = q.get("id"); idn && idn->type == JVal::Num) b.id = numId(idn->n);
                b.w = float(q.num("w", 0));
                b.h = float(q.num("h", 0));
                b.r = float(q.num("r", 0));
                b.material = q.str("material", "liquid");
                b.hasPos = q.has("x") && q.has("y");
                b.x = float(q.num("x", 0));
                b.y = float(q.num("y", 0));
                b.dz = finite(float(q.num("dz", 0.015)));
                b.ox = finite(float(q.num("ox", 0)));
                b.oy = finite(float(q.num("oy", 0)));
                parseColor(q.get("tint"), b.tint);
                parseColor(q.get("fill"), b.fill);
                if (const JVal *h = q.get("hole")) {
                    if (h->type == JVal::Bool) {
                        b.hole.on = h->b;
                    } else if (h->type == JVal::Obj) {
                        b.hole.on = true;
                        b.hole.shadow = std::clamp(finite(float(h->num("shadow", 0.35))), 0.f, 1.f);
                        b.hole.y = std::clamp(finite(float(h->num("y", 9))), -200.f, 200.f);
                        b.hole.blur = std::clamp(finite(float(h->num("blur", 27))), 0.f, 400.f);
                        parseColor(h->get("fill"), b.hole.fill);
                        readEdges(h->get("edges"), b.hole);
                        if (const JVal *c = h->get("clip"); c && c->type == JVal::Arr && c->a.size() == 4) {
                            bool ok = true;
                            float v[4];
                            for (int i = 0; i < 4; i++) {
                                ok &= c->a[size_t(i)].type == JVal::Num && std::isfinite(c->a[size_t(i)].n);
                                v[i] = ok ? float(c->a[size_t(i)].n) : 0.f;
                            }
                            if (ok && v[2] > v[0] && v[3] > v[1]) {
                                b.hole.hasClip = true;
                                b.hole.cx0 = v[0]; b.hole.cy0 = v[1]; b.hole.cx1 = v[2]; b.hole.cy1 = v[3];
                            }
                        }
                    }
                }
                readPhase(q, b.ph);
                if (b.id.empty() || b.id.size() > 128 || b.w < 1 || b.h < 1) continue;
                ss.slabs.push_back(b);
            }
        }
        // v3 plates (G1): at most kMaxPlates, clipped to the texture
        if (const JVal *pl = s.get("plates"); pl && pl->type == JVal::Arr) {
            int index = 0;
            for (const JVal &q : pl->a) {
                if (q.type != JVal::Obj) { index++; continue; }
                PlateSpec p;
                p.id = q.str("id", "");
                if (const JVal *idn = q.get("id"); idn && idn->type == JVal::Num) p.id = numId(idn->n);
                if (p.id.empty()) p.id = "p" + std::to_string(index);
                if (p.id.size() > 128) p.id = p.id.substr(0, 128);
                index++;
                p.material = q.str("material", "liquid");
                p.x = finite(float(q.num("x", 0)));
                p.y = finite(float(q.num("y", 0)));
                p.w = finite(float(q.num("w", 0)));
                p.h = finite(float(q.num("h", 0)));
                p.r = q.has("r") ? std::max(0.f, finite(float(q.num("r", 0)))) : 0.5f * std::min(p.w, p.h);
                readPhase(q, p.ph);
                parseColor(q.get("tint"), p.tint);
                parseColor(q.get("fill"), p.fill);
                p.occluder = q.boolean("occluder", false);
                if (q.has("shadow")) p.shadow = std::clamp(finite(float(q.num("shadow", -1))), 0.f, 1.f);
                const float x0 = std::max(0.f, p.x), y0 = std::max(0.f, p.y);
                const float x1 = std::min(float(ss.texW), p.x + p.w), y1 = std::min(float(ss.texH), p.y + p.h);
                if (x1 - x0 < 1 || y1 - y0 < 1 || ss.plates.size() >= size_t(kMaxPlates)) {
                    if (ss.droppedPlates.size() < size_t(kMaxListedDrops)) ss.droppedPlates.push_back(p.id);
                    ss.droppedPlatesN++;
                    continue;
                }
                p.r = std::min(p.r, 0.5f * std::min(x1 - x0, y1 - y0));
                p.x = x0; p.y = y0; p.w = x1 - x0; p.h = y1 - y0;
                ss.plates.push_back(p);
            }
        }
        if (s.has("coverDz")) ss.coverDz = std::clamp(finite(float(s.num("coverDz", 0.001))), -0.5f, 0.5f);
        if (const JVal *m = s.get("masks"); m && m->type == JVal::Arr) {
            for (const JVal &q : m->a) {
                if (q.type != JVal::Obj || ss.masks.size() >= size_t(kMaxExtraMasks)) continue;
                MaskSpec k{finite(float(q.num("x", 0))), finite(float(q.num("y", 0))), finite(float(q.num("w", 0))),
                           finite(float(q.num("h", 0))), finite(float(q.num("dz", 0)))};
                if (k.w >= 1 && k.h >= 1 && k.w < 20000 && k.h < 20000) ss.masks.push_back(k);
            }
        }
        ss.scaleFromOverlay = s.str("scaleFrom", "main") == "overlay";
        out.surfaces.push_back(std::move(ss));
    }
    return true;
}

std::string sanitizeKey(const std::string &s) {
    std::string o;
    for (char c : s) o += (std::isalnum((unsigned char)c) || c == '.' || c == '_' || c == '-') ? c : '_';
    return o.substr(0, 100);
}


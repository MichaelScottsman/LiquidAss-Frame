            if (!s->dropped.empty()) {
                o += ", \"dropped\": [";
                size_t n = 0;  // the first kMaxListedDrops (counts.dropped has them all)
                for (const std::string &id : s->dropped) {
                    if (n == size_t(kMaxListedDrops)) break;
                    o += (n++ ? ", " : "") + jsonEscape(id);
                }
                o += "]";
            }
            // v3: the plates drawn (in the backdrop region) and those left out
            o += ", \"plates\": [";
            for (size_t i = 0; i < s->plates.size(); i++) o += (i ? ", " : "") + jsonEscape(s->plates[i].s.id);
            o += "]";
            if (!s->spec.droppedPlates.empty()) {
                o += ", \"droppedPlates\": [";
                for (size_t i = 0; i < s->spec.droppedPlates.size(); i++) o += (i ? ", " : "") + jsonEscape(s->spec.droppedPlates[i]);
                o += "]";
            }
